/** Haversine 거리 (km) — 정렬용이므로 정밀도보다 속도 우선 */
function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLng = (lng2 - lng1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/** lat/lng → 가장 가까운 시군구 행정구역코드 (10자리) */
export function latLngToAreaNo(lat: number, lng: number): string {
  let bestCode = AREA_TABLE[0].code;
  let bestDist = Infinity;
  for (const entry of AREA_TABLE) {
    const d = haversineKm(lat, lng, entry.lat, entry.lng);
    if (d < bestDist) {
      bestDist = d;
      bestCode = entry.code;
    }
  }
  return bestCode;
}
